"""景点营业时间知识库 —— 为热门景点提供精确的营业时间和闭馆日数据。

当高德 MCP 返回中未包含开放时间，或 LLM 未填写时，
用此知识库做兜底，避免博物馆被排到夜间或闭馆日。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Set


@dataclass(frozen=True)
class AttractionHours:
    """单个景点的营业时间记录。"""

    opening_time: str = "09:00"
    closing_time: str = "17:00"
    last_entry_time: Optional[str] = None
    # 闭馆星期，周一为 0，周日为 6；空列表表示全年无休
    closed_weekdays: tuple = ()
    # 季节性营业时间变化（月份 -> (opening, closing)）
    seasonal_hours: Optional[Dict[int, tuple]] = None
    # 是否需要提前预约
    requires_booking: bool = False
    # 预约提前天数
    booking_advance_days: int = 0
    # 景点强度等级：1=轻松, 2=中等, 3=高强度（用于体力曲线）
    intensity_level: int = 2
    # 建议游玩时长（分钟）
    recommended_duration: int = 120
    # 门票参考价（元）
    reference_ticket_price: Optional[int] = None
    # 类别标签
    category: str = "景点"

    def get_hours_for_date(self, month: int = 1) -> tuple[str, str]:
        """获取指定月份的营业时间。"""
        if self.seasonal_hours and month in self.seasonal_hours:
            return self.seasonal_hours[month]
        return self.opening_time, self.closing_time


